//! (kind, allowed contexts, deprecation, source documentation path).
//! The `source:` field on each row points back to the corresponding `.adoc`
//! file under `repos_to_compare/tcdocs-main/` for reference only — it is
//! NOT a build input. This data was originally seeded from an automated
//! pass over tcdocs that proved imperfect; entries are now human-reviewed
//! and edited directly here. Do not regenerate from tcdocs without a manual
//! pass.
//!
//! Queries over this data live in `crate::marker_defs`. The public-facing
//! catalog wraps both and lives in `crate::markers`.

